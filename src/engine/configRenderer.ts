import type { Settings, Rule, Endpoint, Protocol } from '../types'

/**
 * AnTun 配置渲染器
 * 把用户设置渲染成 mihomo 兼容的 YAML（核心按需下载，不随包分发）。
 * 移植自原版工程笔记的关键经验：
 *  1) DNS nameserver 只放国外解析器，删掉国内解析器（并发查询取最快，国内 DNS 靠 RTT 必胜）；
 *  2) respect-rules + IP-CIDR 把解析器地址钉到隧道 + proxy-server-nameserver 直连，三者缺一不可；
 *  3) 订阅 ws/grpc/h2 参数折叠进 ws-opts/grpc-opts/h2-opts，顶层 path/host 会被 mihomo 静默忽略；
 *  4) 字段白名单，未知字段会让整个配置解析失败。
 */

const FOREIGN_DNS = ['8.8.8.8', '1.1.1.1', '1.0.0.1']

/** 折叠分享链接的传输参数（复刻 normalizeTransport） */
export function normalizeShareLink(link: string): Record<string, unknown> | null {
  try {
    const url = new URL(link)
    const protocol = url.protocol.replace(':', '').toLowerCase()
    if (!['vless', 'vmess', 'trojan', 'ss'].includes(protocol)) return null
    const q = url.searchParams
    const type = q.get('type') || 'tcp'
    const out: Record<string, unknown> = {
      name: decodeURIComponent(url.hash.slice(1) || 'node'),
      type: protocol,
      server: url.hostname,
      port: Number(url.port || 443),
      network: type,
      tls: q.get('security') === 'tls' || q.get('sni') !== null,
    }
    const path = q.get('path') || ''
    const host = q.get('host') || ''
    if (type === 'ws') {
      out['ws-opts'] = { path, headers: host ? { Host: host } : {} }
    } else if (type === 'grpc') {
      out['grpc-opts'] = { 'grpc-service-name': q.get('serviceName') || path }
    } else if (type === 'h2' || type === 'http') {
      out['h2-opts'] = { path, host: host ? host.split(',') : [] }
    }
    return out
  } catch {
    return null
  }
}

export function renderConfig(settings: Settings, rules: Rule[], endpoint: Endpoint | null): string {
  const { mixedPort, apiPort, allowLan, ipFamily, captureMode, dnsMode, dnsCustom, proxyMode } = settings
  const dnsList = dnsMode === 'custom' && dnsCustom.trim()
    ? dnsCustom.split(/[\n,]/).map((s) => s.trim()).filter(Boolean)
    : FOREIGN_DNS
  const dnsEnabled = dnsMode !== 'off'

  const lines: string[] = []
  lines.push('# Generated by AnTun — 轻量跨端网络客户端')
  lines.push(`mixed-port: ${mixedPort}`)
  lines.push(`allow-lan: ${allowLan}`)
  lines.push('bind-address: 127.0.0.1')
  lines.push('mode: rule')
  lines.push('log-level: info')
  lines.push(`ipv6: ${ipFamily !== 'v4'}`)
  lines.push(`external-controller: 127.0.0.1:${apiPort}`)
  lines.push('tcp-concurrent: true')
  lines.push('unified-delay: true')

  // DNS：国外解析器 + respect-rules + 钉住解析器地址（三条缺一不可）
  if (dnsEnabled) {
    lines.push('dns:')
    lines.push('  enable: true')
    lines.push(`  ipv6: ${ipFamily !== 'v4'}`)
    lines.push('  respect-rules: true')
    lines.push('  proxy-server-nameserver:')
    FOREIGN_DNS.forEach((d) => lines.push(`    - ${d}`))
    lines.push('  nameserver:')
    dnsList.forEach((d) => lines.push(`    - ${d}`))
  }

  // 代理节点：用户锁定端点优先，否则由扫描器注入
  lines.push('proxies:')
  if (endpoint) {
    lines.push(`  - name: "AnTun ${endpoint.protocol.toUpperCase()}"`)
    lines.push(`    type: ${endpoint.protocol === 'awg' || endpoint.protocol === 'wg' ? 'wireguard' : 'masque'}`)
    lines.push(`    server: ${endpoint.host}`)
    lines.push(`    port: ${endpoint.port}`)
  } else {
    lines.push('  - name: "DIRECT-PLACEHOLDER"')
    lines.push('    type: direct')
  }

  lines.push('proxy-groups:')
  lines.push('  - name: WARP')
  lines.push('    type: select')
  lines.push('    proxies:')
  lines.push(endpoint ? `      - "AnTun ${endpoint.protocol.toUpperCase()}"` : '      - DIRECT')
  lines.push('      - DIRECT')
  lines.push('  - name: auto')
  lines.push('    type: url-test')
  lines.push('    url: http://www.gstatic.com/generate_204')
  lines.push('    interval: 300')
  lines.push('    proxies:')
  lines.push(endpoint ? `      - "AnTun ${endpoint.protocol.toUpperCase()}"` : '      - DIRECT')

  // 规则
  lines.push('rules:')
  if (dnsEnabled) {
    FOREIGN_DNS.forEach((d) => lines.push(`  - IP-CIDR,${d}/32,WARP`))
  }
  lines.push('  - IP-CIDR,10.0.0.0/8,DIRECT,no-resolve')
  lines.push('  - IP-CIDR,172.16.0.0/12,DIRECT,no-resolve')
  lines.push('  - IP-CIDR,192.168.0.0/16,DIRECT,no-resolve')
  lines.push('  - IP-CIDR,127.0.0.0/8,DIRECT,no-resolve')

  if (proxyMode === 'global') {
    lines.push('  - MATCH,WARP')
  } else if (proxyMode === 'bypass-mainland') {
    lines.push('  - GEOSITE,cn,DIRECT')
    lines.push('  - GEOIP,cn,DIRECT')
    lines.push('  - MATCH,WARP')
  } else {
    rules.filter((r) => r.enabled).forEach((r) => {
      const value = r.value ? `,${r.value}` : ''
      lines.push(`  - ${r.type}${value},${r.policy}`)
    })
  }

  // TUN 全局模式
  if (captureMode === 'tun') {
    lines.push('tun:')
    lines.push('  enable: true')
    lines.push('  stack: gvisor')
    lines.push('  dns-hijack:')
    lines.push('    - any:53')
    lines.push('  auto-route: true')
  }
  return lines.join('\n') + '\n'
}

/** 生成诊断文本（供日志页「复制诊断信息」） */
export function renderDiagnostics(settings: Settings, platform: string, conn: { connected: boolean; exitIp: string; protocol: Protocol }) {
  return [
    'AnTun Diagnostics',
    `platform=${platform}`,
    `version=1.0.0`,
    `connected=${conn.connected}`,
    `protocol=${conn.protocol}`,
    `exitIp=${conn.exitIp || '-'}`,
    `mixedPort=${settings.mixedPort}`,
    `apiPort=${settings.apiPort}`,
    `captureMode=${settings.captureMode}`,
    `dnsMode=${settings.dnsMode}`,
    `proxyMode=${settings.proxyMode}`,
    `controlCode=${settings.controlCode}`,
  ].join('\n')
}
